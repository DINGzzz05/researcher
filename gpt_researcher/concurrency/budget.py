"""Per-research-unit fan-out budget.

The plan that decides how many sub-queries (and therefore how many URL fetches)
a research unit performs is generated by an LLM from untrusted input. Nothing in
the pipeline bounds it: ``generate_sub_queries`` asks for three, but a model that
returns twenty gets twenty, each of which scrapes up to ``MAX_SEARCH_RESULTS_PER_QUERY``
pages. That is both a cost problem and an amplification primitive - one user
question becomes hundreds of outbound requests.

A ``TaskBudget`` caps the total, not the instantaneous rate: rate and
concurrency are enforced by :mod:`gpt_researcher.concurrency.limits`. Truncating
is deliberate - the alternative (raising) turns an over-eager plan into a failed
report, and the downstream context is token-capped anyway, so the extra sources
would have been discarded.

The budget travels in a :class:`~contextvars.ContextVar`, so it reaches the
scraper several call layers down without threading a parameter through
``ResearchConductor``, ``BrowserManager`` and ``Scraper``. Each
``GPTResearcher.conduct_research`` call installs a fresh budget, which means
multi-agent sections and deep-research branches each get their own allowance
rather than sharing one and starving each other.
"""

from __future__ import annotations

import logging
from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass

from .settings import load

logger = logging.getLogger(__name__)


@dataclass
class TaskBudget:
    """Cumulative fan-out allowance for one research unit.

    A cap of 0 means unlimited; the counters still accumulate so callers can
    report what a run actually used.
    """

    max_urls: int = 0
    max_subqueries: int = 0
    max_sections: int = 0
    urls_started: int = 0
    subqueries_started: int = 0
    sections_started: int = 0
    urls_dropped: int = 0
    subqueries_dropped: int = 0
    sections_dropped: int = 0

    def _allow(
        self,
        items,
        maximum: int,
        started_attr: str,
        dropped_attr: str,
        label: str,
    ) -> list:
        planned = list(items or [])
        if maximum and maximum > 0:
            remaining = max(0, maximum - getattr(self, started_attr))
            allowed = planned[:remaining]
            dropped = len(planned) - len(allowed)
            if dropped:
                setattr(self, dropped_attr, getattr(self, dropped_attr) + dropped)
                logger.warning(
                    "Fan-out budget: dropping %d %s (cap %d, %d already started). "
                    "Raise the cap or narrow the query if this loses sources.",
                    dropped, label, maximum, getattr(self, started_attr),
                )
        else:
            allowed = planned
        setattr(self, started_attr, getattr(self, started_attr) + len(allowed))
        return allowed

    def allow_urls(self, urls) -> list:
        return self._allow(urls, self.max_urls, "urls_started", "urls_dropped", "URL fetch(es)")

    def allow_subqueries(self, sub_queries) -> list:
        return self._allow(
            sub_queries, self.max_subqueries, "subqueries_started", "subqueries_dropped", "sub-querie(s)"
        )

    def allow_sections(self, sections) -> list:
        return self._allow(
            sections, self.max_sections, "sections_started", "sections_dropped", "report section(s)"
        )

    @property
    def dropped(self) -> int:
        return self.urls_dropped + self.subqueries_dropped + self.sections_dropped

    def report(self) -> dict[str, int]:
        return {
            "urls": self.urls_started,
            "subqueries": self.subqueries_started,
            "sections": self.sections_started,
            "dropped": self.dropped,
        }


_CURRENT: ContextVar[TaskBudget | None] = ContextVar(
    "gpt_researcher_task_budget", default=None
)


def current_budget() -> TaskBudget | None:
    """The active budget, or None when the caller is outside a research unit."""
    return _CURRENT.get()


def default_budget() -> TaskBudget:
    settings = load()
    return TaskBudget(
        max_urls=settings.max_urls_per_task,
        max_subqueries=settings.max_subqueries,
        max_sections=settings.max_sections,
    )


@contextmanager
def budget_scope(budget: TaskBudget | None = None):
    """Install a budget for the duration of the block.

    Always installs a *fresh* budget unless one is passed explicitly: a
    long-lived process must not carry counters from one research run into the
    next. Concurrency is unaffected - each asyncio Task copies the context at
    creation, so siblings get independent scopes.
    """
    active = budget if budget is not None else default_budget()
    token = _CURRENT.set(active)
    try:
        yield active
    finally:
        _CURRENT.reset(token)
